using System.Net;
using System.Text.Json;
using System.Text.Json.Serialization;
using Microsoft.Extensions.DependencyInjection;
using RequestsManagement.Api.Data;
using RequestsManagement.Api.Domain;
using RequestsManagement.Tests.Infrastructure;

namespace RequestsManagement.Tests.Integration;

[Collection("Database")]
public sealed class GetRequestsFilteringTests : IAsyncLifetime
{
    private readonly ApiFactory _factory;
    private readonly HttpClient _client;

    // Shared JsonSerializerOptions that match the API's serialisation contract:
    // camelCase properties (ASP.NET Core default) + enums as strings.
    private static readonly JsonSerializerOptions JsonOpts = new()
    {
        PropertyNameCaseInsensitive = true,
        Converters = { new JsonStringEnumConverter() },
    };

    public GetRequestsFilteringTests(ApiFactory factory)
    {
        _factory = factory;
        _client  = factory.CreateClient();
    }

    // xUnit creates a new GetRequestsFilteringTests instance per [Fact], so
    // InitializeAsync runs before each test method — clean slate every time.
    public async Task InitializeAsync()
    {
        await _factory.ResetAsync();
        await SeedAsync();
    }

    public Task DisposeAsync() => Task.CompletedTask;

    // ── Tests ─────────────────────────────────────────────────────────────────

    [Fact]
    public async Task GetRequests_FilterByStatusCompleted_Returns200WithExactlyTwoItems()
    {
        // Act
        var response = await _client.GetAsync("/api/requests?status=Completed");

        // Assert — HTTP status
        Assert.Equal(HttpStatusCode.OK, response.StatusCode);

        // Assert — response body
        var json   = await response.Content.ReadAsStringAsync();
        var result = JsonSerializer.Deserialize<PagedResponse>(json, JsonOpts)!;

        Assert.Equal(2, result.TotalCount);
        Assert.Equal(2, result.Items.Count);
        Assert.All(result.Items, item =>
            Assert.Equal(RequestStatus.Completed, item.Status));
    }

    [Fact]
    public async Task GetRequests_Page2Size2_ReturnsCorrectSliceOfFive()
    {
        // Default sort: createdAt DESC, Id DESC (tiebreaker).
        // All 5 seeds share the same CreatedAt, so the effective order is Id DESC:
        //   [1] Epsilon  [2] Delta  [3] Gamma  [4] Beta  [5] Alpha
        // page=2 &pageSize=2 → skip 2, take 2 → Gamma, Beta (in that order).
        var response = await _client.GetAsync("/api/requests?page=2&pageSize=2");

        Assert.Equal(HttpStatusCode.OK, response.StatusCode);

        var json   = await response.Content.ReadAsStringAsync();
        var result = JsonSerializer.Deserialize<PagedResponse>(json, JsonOpts)!;

        Assert.Equal(5, result.TotalCount);
        Assert.Equal(3, result.TotalPages);
        Assert.Equal(2, result.Items.Count);
        Assert.Equal(["Gamma", "Beta"], result.Items.Select(i => i.Title));
    }

    [Fact]
    public async Task GetRequests_SortByTitleAsc_ReturnsTitlesInAlphabeticalOrder()
    {
        var response = await _client.GetAsync(
            "/api/requests?sortBy=title&sortDirection=asc&pageSize=5");

        Assert.Equal(HttpStatusCode.OK, response.StatusCode);

        var json   = await response.Content.ReadAsStringAsync();
        var result = JsonSerializer.Deserialize<PagedResponse>(json, JsonOpts)!;

        Assert.Equal(5, result.TotalCount);
        Assert.Equal(
            ["Alpha", "Beta", "Delta", "Epsilon", "Gamma"],
            result.Items.Select(i => i.Title));
    }

    [Fact]
    public async Task GetRequests_FilterSortPage_ReturnsCorrectSingleItem()
    {
        // status=Completed → 2 matches: Alpha, Beta.
        // sortBy=title asc → Alpha (page 1), Beta (page 2).
        var response = await _client.GetAsync(
            "/api/requests?status=Completed&sortBy=title&sortDirection=asc&page=2&pageSize=1");

        Assert.Equal(HttpStatusCode.OK, response.StatusCode);

        var json   = await response.Content.ReadAsStringAsync();
        var result = JsonSerializer.Deserialize<PagedResponse>(json, JsonOpts)!;

        Assert.Equal(2, result.TotalCount);
        Assert.Equal(2, result.TotalPages);
        Assert.Single(result.Items);

        var item = result.Items[0];
        Assert.Equal("Beta", item.Title);
        Assert.Equal(RequestStatus.Completed, item.Status);
    }

    // ── Seed helpers ──────────────────────────────────────────────────────────

    // Inserts 5 deterministic rows: 2 Completed, 2 New, 1 InProgress.
    // Required non-nullable properties are set explicitly; RowVersion is
    // generated by SQL Server and must not be assigned.
    private async Task SeedAsync()
    {
        var now = new DateTime(2024, 6, 1, 0, 0, 0, DateTimeKind.Utc);

        await using var scope = _factory.Services.CreateAsyncScope();
        var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();

        db.Requests.AddRange(
            new Request { Title = "Alpha",   OrganizationName = "Org A", Status = RequestStatus.Completed,  Priority = RequestPriority.High,   CreatedAt = now, UpdatedAt = now },
            new Request { Title = "Beta",    OrganizationName = "Org B", Status = RequestStatus.Completed,  Priority = RequestPriority.Low,    CreatedAt = now, UpdatedAt = now },
            new Request { Title = "Gamma",   OrganizationName = "Org C", Status = RequestStatus.New,        Priority = RequestPriority.Medium, CreatedAt = now, UpdatedAt = now },
            new Request { Title = "Delta",   OrganizationName = "Org D", Status = RequestStatus.New,        Priority = RequestPriority.Low,    CreatedAt = now, UpdatedAt = now },
            new Request { Title = "Epsilon", OrganizationName = "Org E", Status = RequestStatus.InProgress, Priority = RequestPriority.High,   CreatedAt = now, UpdatedAt = now }
        );

        await db.SaveChangesAsync();
    }

    // ── Local response types ──────────────────────────────────────────────────
    // Minimal records that mirror only the fields this test inspects.
    // PropertyNameCaseInsensitive handles the camelCase → PascalCase mapping.

    private sealed record PagedResponse(List<ResponseItem> Items, int TotalCount, int TotalPages);
    private sealed record ResponseItem(int Id, RequestStatus Status, string Title);
}
